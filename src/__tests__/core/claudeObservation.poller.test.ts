import { afterEach, expect, it, vi } from "vitest";
import { createObservationPoller } from "../../core/claudeObservation";
afterEach(() => vi.useRealTimers());
it("coalesces retries during an in-flight snapshot and keeps retry polling owned by the original cleanup", async () => {
  vi.useFakeTimers();
  let resolve!: (v: unknown) => void;
  const request = vi.fn().mockImplementationOnce(() => new Promise(r => { resolve = r; })).mockResolvedValue({ available: true, sessions: [] });
  const apply = vi.fn();
  const poller = createObservationPoller({ request, targets: () => ["session"], apply, interval: 100 });
  const stop = poller.start();
  await vi.advanceTimersByTimeAsync(0);
  poller.retry(); poller.retry(); poller.retry();
  await vi.advanceTimersByTimeAsync(500);
  expect(request).toHaveBeenCalledOnce();
  resolve({ available: true, sessions: [] });
  await vi.advanceTimersByTimeAsync(1);
  expect(request).toHaveBeenCalledTimes(2);
  expect(apply).toHaveBeenCalledTimes(2);
  stop();
  poller.retry();
  await vi.advanceTimersByTimeAsync(500);
  expect(request).toHaveBeenCalledTimes(2);
});
it("polls sequentially only while targets exist and fences stopped/replaced owners", async () => {
  vi.useFakeTimers();
  let targets = ["old"];
  let resolve!: (v: unknown) => void;
  const request = vi.fn().mockImplementationOnce(() => new Promise(r => { resolve = r; })).mockResolvedValue({ available: true, sessions: [] });
  const apply = vi.fn();
  const poller = createObservationPoller({ request, targets: () => targets, apply, interval: 100 });
  const stopOld = poller.start();
  await vi.advanceTimersByTimeAsync(500);
  expect(request).toHaveBeenCalledTimes(1);
  targets = ["new"];
  const stopNew = poller.start();
  stopOld();
  resolve({ available: true, sessions: [] });
  await vi.advanceTimersByTimeAsync(0);
  expect(apply).toHaveBeenCalledTimes(1);
  expect(apply.mock.calls[0][1]).toEqual(["new"]);
  targets = [];
  await vi.advanceTimersByTimeAsync(100);
  expect(request).toHaveBeenCalledTimes(2);
  stopNew();
  await vi.advanceTimersByTimeAsync(500);
  expect(request).toHaveBeenCalledTimes(2);
});
